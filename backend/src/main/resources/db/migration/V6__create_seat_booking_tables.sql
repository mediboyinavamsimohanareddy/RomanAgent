-- V6__create_seat_booking_tables.sql

CREATE TABLE bus_seat_layouts (
    id VARCHAR(36) PRIMARY KEY,
    vehicle_id VARCHAR(36) NOT NULL,
    layout_name VARCHAR(50) NOT NULL,
    coach_type VARCHAR(30) NOT NULL, -- e.g. SEATER_2X2, SLEEPER_2X1, SLEEPER_2X2
    total_rows INT NOT NULL,
    total_cols INT NOT NULL,
    total_seats INT NOT NULL,
    has_upper_deck BOOLEAN DEFAULT FALSE,
    CONSTRAINT fk_seat_layouts_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(id)
);

CREATE TABLE bus_seats (
    id VARCHAR(36) PRIMARY KEY,
    layout_id VARCHAR(36) NOT NULL,
    seat_number VARCHAR(10) NOT NULL, -- e.g. 1A, 1B, L1, U1
    row_num INT NOT NULL,
    col_num INT NOT NULL,
    deck VARCHAR(10) DEFAULT 'LOWER', -- LOWER / UPPER
    seat_type VARCHAR(20) DEFAULT 'SEATER', -- SEATER, SLEEPER_SINGLE, SLEEPER_DOUBLE
    is_window BOOLEAN DEFAULT FALSE,
    extra_fare DECIMAL(10,2) DEFAULT 0.00,
    CONSTRAINT fk_bus_seats_layout FOREIGN KEY (layout_id) REFERENCES bus_seat_layouts(id),
    CONSTRAINT uk_layout_seat UNIQUE(layout_id, seat_number)
);

CREATE TABLE service_departures (
    id VARCHAR(36) PRIMARY KEY,
    bus_service_id VARCHAR(36) NOT NULL,
    departure_date DATE NOT NULL,
    status VARCHAR(20) DEFAULT 'SCHEDULED',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_service_departures_bus_service FOREIGN KEY (bus_service_id) REFERENCES bus_services(id),
    CONSTRAINT uk_service_departure_date UNIQUE(bus_service_id, departure_date)
);

CREATE TABLE seat_inventories (
    id VARCHAR(36) PRIMARY KEY,
    service_departure_id VARCHAR(36) NOT NULL,
    bus_seat_id VARCHAR(36) NOT NULL,
    status VARCHAR(20) DEFAULT 'AVAILABLE', -- AVAILABLE, HELD, BOOKED
    hold_token VARCHAR(36),
    hold_expires_at TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_seat_inventories_departure FOREIGN KEY (service_departure_id) REFERENCES service_departures(id),
    CONSTRAINT fk_seat_inventories_seat FOREIGN KEY (bus_seat_id) REFERENCES bus_seats(id),
    CONSTRAINT uk_departure_seat UNIQUE(service_departure_id, bus_seat_id)
);

CREATE INDEX idx_seat_inv_lookup ON seat_inventories(service_departure_id, status);

CREATE TABLE seat_bookings (
    id VARCHAR(36) PRIMARY KEY,
    booking_reference VARCHAR(30) UNIQUE NOT NULL,
    itinerary_id VARCHAR(36),
    service_departure_id VARCHAR(36) NOT NULL,
    passenger_count INT NOT NULL,
    total_fare DECIMAL(10,2) NOT NULL,
    status VARCHAR(20) DEFAULT 'CONFIRMED', -- HELD, CONFIRMED, CANCELLED
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_bookings_departure FOREIGN KEY (service_departure_id) REFERENCES service_departures(id)
);

CREATE TABLE booking_passengers (
    id VARCHAR(36) PRIMARY KEY,
    booking_id VARCHAR(36) NOT NULL,
    bus_seat_id VARCHAR(36) NOT NULL,
    seat_number VARCHAR(10) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    gender VARCHAR(10) NOT NULL,
    age INT NOT NULL,
    CONSTRAINT fk_passengers_booking FOREIGN KEY (booking_id) REFERENCES seat_bookings(id),
    CONSTRAINT fk_passengers_seat FOREIGN KEY (bus_seat_id) REFERENCES bus_seats(id)
);

